/**
 * Making `se` runnable from any shell on any machine, reproducibly.
 *
 * `bun link` is not enough, and the gap is not cosmetic. It installs a launcher
 * into bun's own bin directory -- `%USERPROFILE%\.bun\bin` on Windows, which is
 * not on PATH by default -- so the command works in whichever shell the
 * installer happened to patch by hand and reports "command not found" in every
 * other one. That is indistinguishable, from the operator's side, from the
 * catalogue being broken, and it is the reason this module exists instead of a
 * paragraph in a README telling each person to patch their own PATH.
 *
 * Two decisions here are deliberate and worth stating:
 *
 *   1. The shims invoke `bun <catalogue>/src/cli.ts` directly. They do not go
 *      through `bun link`'s launcher, so `bun link` is not a prerequisite and
 *      unlinking cannot break them.
 *   2. The absolute path to the running `bun` is embedded, with a fallback to
 *      whatever `bun` is on PATH. A package-manager install of bun (winget,
 *      scoop) puts the binary somewhere that is itself not reliably on PATH, so
 *      a shim that just says `bun` works in the shell that installed it and
 *      fails in the next one. The fallback keeps the shim working if bun later
 *      moves.
 */

import { chmodSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { delimiter, join, resolve, sep } from "node:path";
import { homedir } from "node:os";
import { posix, seHome } from "./util/paths.ts";

/** Marker written into every generated shim, so we never overwrite a user's own. */
export const SHIM_MARKER = "GENERATED by `se install`";

export interface Shim {
  readonly name: string;
  readonly contents: string;
  /** Which shells read this file, for the report. */
  readonly shells: string;
}

/**
 * Compare two directories as the platform's path lookup would.
 *
 * Windows PATH matching is case-insensitive and tolerates a trailing separator;
 * treating `C:\Users\x\.local\bin` and `c:\users\x\.local\bin\` as different
 * directories would make the "is it on PATH" check report a false negative and
 * send the operator off to patch a PATH that was already correct.
 */
function samePath(a: string, b: string): boolean {
  const norm = (p: string): string => {
    let out = resolve(p);
    while (out.length > 3 && (out.endsWith(sep) || out.endsWith("/"))) out = out.slice(0, -1);
    return process.platform === "win32" ? out.toLowerCase() : out;
  };
  return norm(a) === norm(b);
}

/** Directories on the current PATH, resolved and de-duplicated. */
export function pathEntries(pathVar = process.env["PATH"] ?? ""): string[] {
  return pathVar
    .split(delimiter)
    .map((p) => p.trim())
    .filter(Boolean)
    .map((p) => p.replace(/^"|"$/g, ""));
}

export function isOnPath(dir: string, pathVar = process.env["PATH"] ?? ""): boolean {
  return pathEntries(pathVar).some((entry) => samePath(entry, dir));
}

/**
 * Where to put the shims.
 *
 * A directory that is *already* on PATH is preferred over a tidier one that is
 * not, because the install then needs no shell restart, no profile edit and no
 * second step the operator can forget -- which is the whole failure being fixed.
 * `~/.se/bin` is the last resort precisely because it requires that second step.
 */
export function chooseBinDir(explicit?: string): { dir: string; reason: string } {
  if (explicit) return { dir: resolve(explicit), reason: "--bin-dir" };

  const candidates = [join(homedir(), ".local", "bin"), join(homedir(), "bin")];

  for (const dir of candidates) {
    if (isOnPath(dir)) return { dir, reason: "already on PATH" };
  }
  for (const dir of candidates) {
    if (existsSync(dir)) return { dir, reason: "exists, but is not on PATH" };
  }
  return { dir: join(seHome(), "bin"), reason: "created; not on PATH" };
}

/**
 * The launcher scripts.
 *
 * One per shell family. Windows uses the .cmd shim in both PowerShell and
 * cmd.exe; other platforms also receive the PowerShell shim when available.
 */
export function shims(catalogueRoot: string, bunPath: string): Shim[] {
  const cli = join(catalogueRoot, "src", "cli.ts");
  const cliPosix = posix(cli);
  const bunPosix = posix(bunPath);
  const sq = (s: string): string => s.replace(/'/g, "''");

  const result: Shim[] = [
    {
      name: "se",
      shells: "sh, bash, zsh, Git Bash",
      contents: [
        "#!/bin/sh",
        "# " + SHIM_MARKER + ". Do not edit; rerun `se install` instead.",
        "# Falls back to whatever bun is on PATH if the recorded one has moved.",
        'BUN="' + bunPosix + '"',
        '[ -x "$BUN" ] || BUN=bun',
        'exec "$BUN" "' + cliPosix + '" "$@"',
        "",
      ].join("\n"),
    },
    {
      name: "se.cmd",
      shells: "cmd.exe, PowerShell",
      contents: [
        "@echo off",
        "rem " + SHIM_MARKER + '. Do not edit; rerun "se install" instead.',
        'set "SE_BUN=' + bunPath + '"',
        'if not exist "%SE_BUN%" set "SE_BUN=bun"',
        '"%SE_BUN%" "' + cli + '" %*',
        "exit /b %ERRORLEVEL%",
        "",
      ].join("\r\n"),
    },
  ];

  // On Windows, PowerShell prefers .ps1 over .cmd during command discovery.
  // A Restricted execution policy then blocks the launcher before it can run,
  // even though the equivalent .cmd is valid. The .cmd file works in both
  // PowerShell and cmd.exe, so do not shadow it with an unusable script.
  if (process.platform !== "win32") {
    result.push({
      name: "se.ps1",
      shells: "PowerShell, pwsh",
      contents: [
        "#!/usr/bin/env pwsh",
        "# " + SHIM_MARKER + ". Do not edit; rerun `se install` instead.",
        "$bun = '" + sq(bunPath) + "'",
        "if (-not (Test-Path -LiteralPath $bun)) { $bun = 'bun' }",
        "& $bun '" + sq(cli) + "' @args",
        "exit $LASTEXITCODE",
        "",
      ].join("\r\n"),
    });
  }

  return result;
}

export interface WrittenShim {
  readonly path: string;
  readonly shells: string;
  readonly state: "written" | "unchanged" | "refused-foreign";
}

/**
 * Write the shims, never clobbering a file this tool did not generate.
 *
 * A `se` already on PATH may be someone else's program. Overwriting it would
 * break whatever depended on it, silently and from a command whose stated job
 * was to install something else.
 */
export function writeShims(dir: string, catalogueRoot: string, bunPath: string): WrittenShim[] {
  mkdirSync(dir, { recursive: true });
  const written: WrittenShim[] = [];

  // Clean up the generated Windows launcher from older installs. Leave a
  // hand-written PowerShell script alone; only remove our marked artifact.
  if (process.platform === "win32") {
    const ps1 = join(dir, "se.ps1");
    if (existsSync(ps1) && readFileSync(ps1, "utf8").includes(SHIM_MARKER)) rmSync(ps1);
  }

  for (const shim of shims(catalogueRoot, bunPath)) {
    const path = join(dir, shim.name);
    if (existsSync(path)) {
      const existing = readFileSync(path, "utf8");
      if (!existing.includes(SHIM_MARKER)) {
        written.push({ path, shells: shim.shells, state: "refused-foreign" });
        continue;
      }
      if (existing === shim.contents) {
        written.push({ path, shells: shim.shells, state: "unchanged" });
        continue;
      }
    }
    writeFileSync(path, shim.contents, "utf8");
    // The sh shim must be executable; on Windows the mode is ignored, and on
    // POSIX a shim without +x is a "command not found" with a confusing cause.
    if (!shim.name.includes(".")) {
      try {
        chmodSync(path, 0o755);
      } catch {
        // Not all filesystems carry a mode. The .cmd/.ps1 shims still work.
      }
    }
    written.push({ path, shells: shim.shells, state: "written" });
  }
  return written;
}

/** Per-shell instructions for putting `dir` on PATH, for when it is not. */
export function pathInstructions(dir: string): string[] {
  if (process.platform === "win32") {
    return [
      "PowerShell, persistent for your user (then open a new terminal):",
      "",
      "  [Environment]::SetEnvironmentVariable('Path'," +
        " [Environment]::GetEnvironmentVariable('Path','User') + ';" + dir + "', 'User')",
      "",
      "Or let this command do it for you:",
      "",
      "  se install --add-path",
    ];
  }
  return [
    "Add it to your shell profile (then open a new terminal):",
    "",
    "  echo 'export PATH=\"" + posix(dir) + ":$PATH\"' >> ~/.profile",
    "",
    "Or let this command do it for you:",
    "",
    "  se install --add-path",
  ];
}
